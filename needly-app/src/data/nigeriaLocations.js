export function uniqueNigeriaLocations(locations = NIGERIA_MAJOR_LOCATIONS) {
  const seen = new Set();
  return locations.filter((location) => {
    const key = `${location.state}-${location.city}-${location.area || ""}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

export function nigeriaLocationLabel(location) {
  if (!location) return "";
  if (location.area && location.area !== location.city) {
    return `${location.area}, ${location.city}, ${location.state}`;
  }
  return `${location.city}, ${location.state}`;
}
